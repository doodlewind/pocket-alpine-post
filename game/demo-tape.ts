/** Expand the shipped RLE stream to the controller's one-mask-per-frame input. */
export function alpineAttractTape(): number[] {
  const masks: number[] = [];
  for (const [mask, count] of ALPINE_TAPE_RUNS) {
    for (let i = 0; i < count; i++) masks.push(mask >>> 0);
  }
  if (masks.length !== ALPINE_TAPE_FRAMES) {
    throw new Error(`Alpine attract tape: expected ${ALPINE_TAPE_FRAMES} frames, got ${masks.length}`);
  }
  return masks;
}
